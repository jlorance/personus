#!/usr/bin/env bun
/**
 * Generate `docs/index.md` — the reserved OKF bundle listing — from the
 * frontmatter of every concept file. Grouped by top-level section, with title,
 * status, and description. Regenerate after adding/moving docs.
 *
 * Usage: `bun scripts/docs/gen-index.mjs`
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFrontmatter, RESERVED, walkMarkdown } from './lib.mjs';

const DOCS = resolve(dirname(fileURLToPath(import.meta.url)), '../../docs');

const SECTIONS = [
  [
    'foundation',
    'Foundation',
    'Cross-cutting canon — vision, principles, architecture, data model, agents, auth.',
  ],
  ['domains', 'Domains', 'Product areas: PRDs, feature specs, schema specs.'],
  ['decisions', 'Decisions', 'Architecture decision records (ADRs).'],
  ['guides', 'Guides', 'Methodology and how-to.'],
  ['research', 'Research', 'External landscape and integration studies.'],
  ['patterns', 'Patterns', 'UX and design pattern studies.'],
  ['business-model', 'Business model', 'Pricing, growth, positioning.'],
  ['qa', 'QA', 'Quality-assurance conventions.'],
  ['archive', 'Archive', 'Quarantined stale / point-in-time material (superseded).'],
];
const STATUS_BADGE = {
  current: '🟢 current',
  planned: '🔵 planned',
  dormant: '🟡 dormant',
  stub: '⚪ stub',
  superseded: '⚫ superseded',
};

const bySection = new Map(SECTIONS.map(([k]) => [k, []]));
for (const file of walkMarkdown(DOCS)) {
  const rel = relative(DOCS, file);
  const base = rel.split('/').pop();
  if (RESERVED.has(base) || rel === '_okf.md') continue;
  const top = rel.split('/')[0];
  if (!bySection.has(top)) continue;
  const { data } = parseFrontmatter(readFileSync(file, 'utf8'));
  bySection.get(top).push({ rel, ...data });
}

const lines = [
  '# Personus knowledge bundle',
  '',
  'An [OKF](https://github.com/GoogleCloudPlatform/knowledge-catalog/blob/main/okf/SPEC.md) knowledge bundle for Personus. Conventions and `status` meanings: [`_okf.md`](/_okf.md). Change history: [`log.md`](/log.md).',
  '',
  '> Generated by `bun scripts/docs/gen-index.mjs` — do not edit by hand.',
  '',
];

let total = 0;
for (const [key, heading, blurb] of SECTIONS) {
  const items = bySection.get(key).sort((a, b) => a.rel.localeCompare(b.rel));
  if (items.length === 0) continue;
  total += items.length;
  lines.push(`## ${heading}`, '', `${blurb}`, '');
  for (const it of items) {
    const badge = STATUS_BADGE[it.status] ?? it.status ?? '';
    const desc = it.description ? ` — ${it.description}` : '';
    lines.push(`- [${it.title ?? it.rel}](/${it.rel}) · ${badge}${desc}`);
  }
  lines.push('');
}

lines.push(
  `_${total} concept files across ${SECTIONS.filter(([k]) => bySection.get(k).length).length} sections._`,
  '',
);
writeFileSync(resolve(DOCS, 'index.md'), lines.join('\n'));
console.log(`gen-index — wrote docs/index.md (${total} files)`);
